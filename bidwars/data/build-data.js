function build() {
  const dataDir = __dirname;
  const catalog = [];
  for (const [cat, def] of Object.entries(CATEGORIES)) {
    const rows = def.entities.map(([name, subcategory, description], idx) => {
      const n = idx + 1;
      return {
        id: `${cat}-${String(n).padStart(2, "0")}`,
        category: cat,
        subcategory,
        name,
        description,
        image: `images/${cat}/${n}.jpg`,
      };
    });
    fs.writeFileSync(path.join(dataDir, `${cat}.json`), JSON.stringify(rows, null, 2) + "\n");
    catalog.push({ id: cat, label: def.label, count: rows.length });
    console.log(`wrote ${cat}.json (${rows.length})`);
  }
  fs.writeFileSync(path.join(dataDir, "index.json"), JSON.stringify(catalog, null, 2) + "\n");
  console.log("wrote index.json", catalog.map((c) => `${c.id}:${c.count}`).join(" "));
}

build();
